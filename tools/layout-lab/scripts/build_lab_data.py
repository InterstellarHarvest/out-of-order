#!/usr/bin/env python3
"""Bundle the lab's JSON into data/lab_data.js, and its images into data/snapshot_assets.js.

Pages opened from file:// cannot fetch JSON, so the page reads these generated scripts.
The JSON files stay authoritative: re-run this after editing any of them.

A canvas that has touched a file:// image can never be read back, which rules out saving
a PNG. snapshot_assets.js carries the same approved bytes as data URLs, which a canvas can
read. It is loaded only when a snapshot is taken, and QA checks it against the approved hashes.
"""
import base64
import json
import re
import struct
from pathlib import Path

LAB = Path(__file__).resolve().parents[1]
ROOT = LAB.parents[1]
PACKAGE = ROOT / "art/ui"
GLYPHS = PACKAGE / "sprites/fonts/locked_pixel_font_atlas.json"


def load(path):
    return json.loads(Path(path).read_text())


SHEET = json.loads((PACKAGE / "m1_approved_sprite_sheet.json").read_text())

# Candidate action glyphs for the utility buttons: the current file of each sprite in each batch,
# never its saved <name>_vN.png versions or the contact sheet. Each batch prefixes its names, so two
# batches can share one. A save naming a glyph from a dropped batch falls back to the default.
GLYPH_DIRS = [("../../art/actions", "", "")]


def png_size(path):
    return list(struct.unpack(">II", path.read_bytes()[16:24]))


action_glyphs = {
    prefix + png.stem: {"file": folder + "/" + png.name, "size": png_size(png),
                        "label": (label + ": " if label else "") + png.stem.replace("_", " ")}
    for folder, prefix, label in GLYPH_DIRS
    for png in sorted((LAB / folder).glob("*.png"))
    if not png.name.startswith("_") and not re.search(r"_v\d+$", png.stem)
}

bundle = {
    "placementDefault": load(LAB / "data/placement.default.json"),
    "comparePresets": load(LAB / "data/compare_presets.json"),
    "measured": load(LAB / "data/measured_shell_regions.json"),
    "glyphs": load(GLYPHS),
    "fonts": load(LAB / "data/fonts.json"),
    "actionGlyphs": action_glyphs,
}
text = "// Generated by scripts/build_lab_data.py. Do not edit.\nwindow.M1_LAB_DATA = "
(LAB / "data/lab_data.js").write_text(text + json.dumps(bundle, indent=1) + ";\n")
print("wrote data/lab_data.js")


def data_url(path):
    return "data:image/png;base64," + base64.b64encode(path.read_bytes()).decode("ascii")


assets = {"layout-final.png": data_url(ROOT / "art/ui/shell/layout-final.png")}
for name, entry in SHEET["sprites"].items():
    if name != "locked_pixel_font_atlas":
        assets[name] = data_url(PACKAGE / entry["package_path"])
for face_id, face in bundle["fonts"].items():
    assets["font:" + face_id] = data_url(LAB / face["atlas"])
for name, glyph in action_glyphs.items():
    assets["glyph:" + name] = data_url(LAB / glyph["file"])
text = "// Generated by scripts/build_lab_data.py. Do not edit.\nwindow.M1_SNAPSHOT_ASSETS = "
(LAB / "data/snapshot_assets.js").write_text(text + json.dumps(assets) + ";\n")
print("wrote data/snapshot_assets.js")
