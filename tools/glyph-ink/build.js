#!/usr/bin/env node
// Builds game/js/glyph-ink.js: for every glyph of every face the game draws, the rows of its box
// that actually hold ink. js/pixeltext.js T.inkRows uses it where a page cannot read a canvas back
// (file://, docs/84 section 7), so the item slip's text is centred exactly as by the pixel scan.
//   node tools/glyph-ink/build.js           write it
//   node tools/glyph-ink/build.js --verify  exit 1 if it no longer matches the font atlases
// Re-run after any font atlas edit (part of the font-edit bookkeeping).
'use strict';
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const ROOT = path.resolve(__dirname, '../..');
const OUT = path.join(ROOT, 'game/js/glyph-ink.js');

function decodePng(buf) {
  let pos = 8, width, height, depth, type, interlace;
  const idat = [];
  while (pos < buf.length) {
    const len = buf.readUInt32BE(pos), t = buf.toString('ascii', pos + 4, pos + 8), body = buf.subarray(pos + 8, pos + 8 + len);
    if (t === 'IHDR') { width = body.readUInt32BE(0); height = body.readUInt32BE(4); depth = body[8]; type = body[9]; interlace = body[12]; }
    if (t === 'IDAT') idat.push(body);
    pos += 12 + len;
  }
  const ch = { 0: 1, 2: 3, 4: 2, 6: 4 }[type];
  if (depth !== 8 || !ch || interlace) throw new Error('unsupported PNG');
  const raw = zlib.inflateSync(Buffer.concat(idat)), stride = width * ch, px = Buffer.alloc(height * stride);
  for (let y = 0; y < height; y++) {
    const f = raw[y * (stride + 1)], line = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    for (let i = 0; i < stride; i++) {
      const a = i >= ch ? px[y * stride + i - ch] : 0, b = y ? px[(y - 1) * stride + i] : 0, c = y && i >= ch ? px[(y - 1) * stride + i - ch] : 0;
      let v = line[i];
      if (f === 1) v += a; else if (f === 2) v += b; else if (f === 3) v += (a + b) >> 1;
      else if (f === 4) { const q = a + b - c, pa = Math.abs(q - a), pb = Math.abs(q - b), pc = Math.abs(q - c); v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c; }
      px[y * stride + i] = v & 255;
    }
  }
  return { width, alpha: (x, y) => (ch === 4 ? px[y * stride + x * 4 + 3] : ch === 2 ? px[y * stride + x * 2 + 1] : 255) };
}

function inkOf(png, g) {
  let top = -1, bottom = -1;
  for (let y = 0; y < g.h; y++) for (let x = 0; x < g.w; x++) {
    if (png.alpha(g.x + x, g.y + y)) { if (top < 0) top = y; bottom = y + 1; break; }
  }
  return top < 0 ? null : [top, bottom];
}

function build() {
  global.window = {};
  require(path.join(ROOT, 'tools/layout-lab/data/lab_data.js'));
  const D = global.window.M1_LAB_DATA;
  const faces = { locked: { atlas: 'art/ui/sprites/fonts/locked_pixel_font_atlas_dark.png', mapping: D.glyphs.mapping } };
  Object.keys(D.fonts).forEach((id) => { faces[id] = { atlas: path.join('tools/layout-lab', D.fonts[id].atlas), mapping: D.fonts[id].mapping }; });
  const out = {};
  Object.keys(faces).sort().forEach((id) => {
    const png = decodePng(fs.readFileSync(path.join(ROOT, faces[id].atlas)));
    out[id] = {};
    Object.keys(faces[id].mapping).forEach((c) => {
      const g = faces[id].mapping[c];
      if (g.w && g.h) { const ink = inkOf(png, g); if (ink) out[id][c] = ink; }
    });
  });
  return '// GENERATED by tools/glyph-ink/build.js from the font atlases. Do not edit.\n'
    + '// Per face, per character: [first, last + 1] ink rows inside its glyph box (js/pixeltext.js T.inkRows).\n'
    + 'window.CYOA_GLYPH_INK = ' + JSON.stringify(out) + ';\n';
}

const text = build();
if (process.argv.includes('--verify')) {
  const ok = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8') === text;
  console.log(ok ? 'OK glyph ink table matches the font atlases' : 'FAIL game/js/glyph-ink.js is stale: run node tools/glyph-ink/build.js');
  process.exitCode = ok ? 0 : 1;
} else {
  fs.writeFileSync(OUT, text);
  console.log('wrote ' + path.relative(ROOT, OUT));
}
